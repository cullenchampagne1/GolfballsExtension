/**
 * Build the server-owned settings policy and the service-worker validation
 * registry from the extension's canonical ESM setting registries.
 *
 * Run this after adding or removing a feature/developer setting. The YAML is
 * intentionally human-editable after generation; running this command again
 * resets it to code defaults and visible state.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { FEATURE_DEFAULTS, FEATURE_FLAGS } from '../src/lib/flags.js';
import { DEV_SETTINGS, defaultDevSettings } from '../src/lib/devSettings.js';
import { CUSTOM_PAGE_SECTIONS } from '../src/lib/customPages.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const extensionRoot = path.resolve(here, '..');
const workspaceRoot = path.resolve(extensionRoot, '..');
const yamlPath = path.join(workspaceRoot, 'api-access-configs', 'golfballs-extension-configuration.yaml');
const registryPath = path.join(extensionRoot, 'settings-registry.js');

// Installation-local dev settings: a shared server policy never forces or hides
// these — each stays a per-install choice. email.localPart guards sender
// identity; emailRelay.notifications is a per-rep opt-in the rep toggles locally.
const INSTALLATION_LOCAL_KEYS = new Set(['email.localPart', 'emailRelay.notifications']);

const featureMeta = Object.fromEntries(FEATURE_FLAGS.map((item) => [item.key, item]));
const developerRows = DEV_SETTINGS.filter((item) => item.type !== 'action');
const developerDefaults = defaultDevSettings();
const scalar = (value) => JSON.stringify(value);

const lines = [
  '# Golfballs extension centrally managed settings.',
  '# value is authoritative when managed is true; hidden removes its UI control.',
  '# email.localPart remains installation-local so a shared policy cannot erase identity.',
  'schema_version: 1',
  'refresh_minutes: 15',
  'developer_section:',
  '  hidden: false',
  'features:',
];
for (const [key, value] of Object.entries(FEATURE_DEFAULTS)) {
  const meta = featureMeta[key];
  lines.push(`  ${key}:`, `    value: ${scalar(value)}`, '    hidden: false', '    managed: true');
  if (meta?.name) lines.push(`    label: ${scalar(meta.name)}`);
}
lines.push('developer_settings:');
for (const row of developerRows) {
  lines.push(
    `  ${row.key}:`,
    `    value: ${scalar(developerDefaults[row.key])}`,
    '    hidden: false',
    `    managed: ${INSTALLATION_LOCAL_KEYS.has(row.key) ? 'false' : 'true'}`,
    `    label: ${scalar(row.label)}`,
  );
}

lines.push('custom_pages:', '  value: true', '  hidden: false', '  managed: true', '  scopes:');
for (const section of CUSTOM_PAGE_SECTIONS) {
  lines.push(
    `    ${section.id}:`,
    '      value: false',
    '      hidden: false',
    '      managed: true',
    `      label: ${scalar(section.label)}`,
  );
}

const registry = {
  schemaVersion: 1,
  features: Object.fromEntries(Object.entries(FEATURE_DEFAULTS).map(([key, value]) => [key, { type: 'bool', default: value }])),
  developerSettings: Object.fromEntries(developerRows.map((row) => [row.key, {
    type: row.type,
    default: developerDefaults[row.key],
    ...(row.min === undefined ? {} : { min: row.min }),
    ...(row.max === undefined ? {} : { max: row.max }),
    ...(row.options ? { options: row.options.map((option) => option.value) } : {}),
  }])),
  customPageScopes: Object.fromEntries(CUSTOM_PAGE_SECTIONS.map((section) => [section.id, {
    type: 'bool',
    default: false,
    pageIds: section.items.map((item) => item.id),
  }])),
  customPages: { type: 'bool', default: true },
};
const registrySource = `/** Generated by scripts/build-remote-settings-config.mjs. */\n(function (root) {\n  'use strict';\n  root.GB_SETTINGS_REGISTRY = Object.freeze(${JSON.stringify(registry, null, 2)});\n})(globalThis);\n`;

const writes = [writeFile(registryPath, registrySource, 'utf8')];
if (!process.argv.includes('--registry-only')) writes.push(writeFile(yamlPath, `${lines.join('\n')}\n`, 'utf8'));
await Promise.all(writes);
console.log(`Wrote ${Object.keys(FEATURE_DEFAULTS).length} features, ${developerRows.length} developer settings, and ${CUSTOM_PAGE_SECTIONS.length} custom-page scopes.`);
