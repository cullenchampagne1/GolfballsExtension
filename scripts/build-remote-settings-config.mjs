/**
 * Build the service-worker validation registry and, when explicitly requested,
 * the deprecated database bootstrap YAML from the canonical ESM registries.
 *
 * Run this after adding or removing a feature/developer setting. Normal runs
 * never touch the legacy YAML. Pass --legacy-seed only when intentionally
 * rebuilding the one-time bootstrap document for a fresh deployment.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { FEATURE_DEFAULTS, FEATURE_FLAG_META } from '../src/lib/flags.js';
import { DEV_SETTINGS, defaultDevSettings } from '../src/lib/devSettings.js';
import { CUSTOM_PAGE_SECTIONS } from '../src/lib/customPages.js';
import { ADMIN_ONLY } from './strip-admin.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const extensionRoot = path.resolve(here, '..');
const workspaceRoot = path.resolve(extensionRoot, '..');
const yamlPath = path.join(workspaceRoot, 'api-access-configs', 'golfballs-extension-configuration.yaml');
const registryPath = path.join(extensionRoot, 'settings-registry.js');

// Admin-only feature/setting keys are NEVER centrally managed: they're admin-
// local code features, absent from the served build. The admin build doesn't
// validate them (admin_bypass), and the consumer must never see them — so both
// the validation registry and the legacy seed always exclude them.
const ADMIN_CONFIG = new Set(ADMIN_ONLY.configKeys || []);
const keep = (key) => !ADMIN_CONFIG.has(key);

// Installation-local dev settings: a shared server policy never forces or hides
// these — each stays a per-install choice. email.localPart guards sender
// identity and is never replaced by a shared policy value.
const INSTALLATION_LOCAL_KEYS = new Set([
  'email.localPart',
  'pageEngine.indexingEnabled',
  'pageEngine.territory',
]);

const featureMeta = Object.fromEntries(FEATURE_FLAG_META.map((item) => [item.key, item]));
const featureDefaultEntries = Object.entries(FEATURE_DEFAULTS).filter(([key]) => keep(key));
const developerRows = DEV_SETTINGS.filter((item) => item.type !== 'action' && keep(item.key));
const developerDefaults = defaultDevSettings();
const scalar = (value) => JSON.stringify(value);

const lines = [
  '# DEPRECATED bootstrap seed for the database-owned Golfballs settings policy.',
  '# Runtime reads and dashboard edits do not use this file.',
  '# value is authoritative when managed is true; hidden removes its UI control.',
  '# email.localPart remains installation-local so a shared policy cannot erase identity.',
  'schema_version: 1',
  'refresh_minutes: 15',
  'developer_section:',
  '  hidden: false',
  'features:',
];
for (const [key, value] of featureDefaultEntries) {
  const meta = featureMeta[key];
  lines.push(`  ${key}:`, `    value: ${scalar(value)}`, '    hidden: false', '    managed: true');
  if (meta?.name) lines.push(`    label: ${scalar(meta.name)}`);
}
lines.push('developer_settings:');
for (const row of developerRows) {
  lines.push(
    `  ${row.key}:`,
    `    value: ${scalar(developerDefaults[row.key])}`,
    '    hidden: false',
    `    managed: ${INSTALLATION_LOCAL_KEYS.has(row.key) ? 'false' : 'true'}`,
    `    label: ${scalar(row.label)}`,
  );
}

lines.push('custom_pages:', '  value: true', '  hidden: false', '  managed: true', '  scopes:');
for (const section of CUSTOM_PAGE_SECTIONS) {
  lines.push(
    `    ${section.id}:`,
    '      value: false',
    '      hidden: false',
    '      managed: true',
    `      label: ${scalar(section.label)}`,
  );
}

const registry = {
  schemaVersion: 1,
  features: Object.fromEntries(featureDefaultEntries.map(([key, value]) => [key, {
    type: 'bool', default: value, label: featureMeta[key]?.name || key,
    managedDefault: true,
  }])),
  developerSettings: Object.fromEntries(developerRows.map((row) => [row.key, {
    type: row.type,
    default: developerDefaults[row.key],
    label: row.label,
    managedDefault: !INSTALLATION_LOCAL_KEYS.has(row.key),
    ...(row.min === undefined ? {} : { min: row.min }),
    ...(row.max === undefined ? {} : { max: row.max }),
    ...(row.options ? { options: row.options.map((option) => option.value) } : {}),
  }])),
  customPageScopes: Object.fromEntries(CUSTOM_PAGE_SECTIONS.map((section) => [section.id, {
    type: 'bool',
    default: false,
    label: section.label,
    managedDefault: true,
    pageIds: section.items.map((item) => item.id),
  }])),
  customPages: { type: 'bool', default: true, label: 'Custom pages', managedDefault: true },
};
const registrySource = `/** Generated by scripts/build-remote-settings-config.mjs. */\n(function (root) {\n  'use strict';\n  root.GB_SETTINGS_REGISTRY = Object.freeze(${JSON.stringify(registry, null, 2)});\n})(globalThis);\n`;

const writes = [writeFile(registryPath, registrySource, 'utf8')];
if (process.argv.includes('--legacy-seed')) writes.push(writeFile(yamlPath, `${lines.join('\n')}\n`, 'utf8'));
await Promise.all(writes);
console.log(`Wrote ${featureDefaultEntries.length} features, ${developerRows.length} developer settings, and ${CUSTOM_PAGE_SECTIONS.length} custom-page scopes (admin-only keys excluded).`);
